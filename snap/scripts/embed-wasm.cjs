// Embeds SENA's WebAssembly (../src/sena) into the Snap's bundle: a Snap
// cannot fetch files of its own at run time.
const { readFileSync, writeFileSync, copyFileSync } = require('node:fs');
const { join } = require('node:path');
const src = join(__dirname, '..', '..', 'src', 'sena');
const out = join(__dirname, '..', 'src', 'generated');
require('node:fs').mkdirSync(out, { recursive: true });
// The glue's async loader would fetch the .wasm by URL; the Snap uses
// initSync with embedded bytes, so that path is removed for the bundler.
const glue = readFileSync(join(src, 'sena_wasm.js'), 'utf8').replace(
  "module_or_path = new URL('sena_wasm_bg.wasm', import.meta.url);",
  "throw new Error('the SENA Snap loads its WebAssembly with initSync');",
);
if (glue.includes('import.meta')) throw new Error('sena_wasm.js changed shape; update scripts/embed-wasm.cjs');
writeFileSync(join(out, 'sena_wasm.js'), glue);
copyFileSync(join(src, 'sena_wasm.d.ts'), join(out, 'sena_wasm.d.ts'));
const b64 = readFileSync(join(src, 'sena_wasm_bg.wasm')).toString('base64');
writeFileSync(join(out, 'wasm-bytes.ts'), `// Generated by scripts/embed-wasm.cjs from ../src/sena; do not edit.\nexport const WASM_BASE64 = ${JSON.stringify(b64)};\n`);
console.log(`embedded ${Math.round(b64.length / 1024)} KiB of base64 wasm`);
